import React, { useEffect, useState } from "react";
import { Link, useParams } from "react-router-dom";
import { FiAlertTriangle, FiArrowLeft, FiCheckCircle, FiDownload, FiPrinter } from "react-icons/fi";
import { useAuth } from "provider/auth";
import { getReport } from "handler/teachmate";
import Markdown from "components/TeachMate/Markdown";
import { downloadReportPdf } from "components/TeachMate/reportPdf";
import "assets/styles/teachmate-report.scss";

const STATES = [
  ["difficult", "Difficult"],
  ["easy", "Easy"],
  ["boring", "Boring"],
  ["engaging", "Engaging"],
];

const formatDate = (value) => new Date(value).toLocaleString(undefined, { dateStyle: "medium", timeStyle: "short" });

function Section({ title, children }) {
  return (
    <section className="tr-section">
      <h2>{title}</h2>
      {children}
    </section>
  );
}

// A printable lesson report generated by TeachMate: /l/:id/report/:reportId
export default function LessonReportPage() {
  const { id, reportId } = useParams();
  const { getAuthHeader } = useAuth();
  const [report, setReport] = useState(null);
  const [error, setError] = useState(null);
  const [highlight, setHighlight] = useState(null);
  const [downloading, setDownloading] = useState(false);
  const [downloadError, setDownloadError] = useState(null);

  const download = async () => {
    setDownloading(true);
    setDownloadError(null);
    try {
      await downloadReportPdf(report);
    } catch (e) {
      console.error(e);
      setDownloadError("Couldn't create the PDF. Try again, or use Print and choose 'Save as PDF'.");
    } finally {
      setDownloading(false);
    }
  };

  useEffect(() => {
    let active = true;
    getReport(getAuthHeader(), reportId)
      .then((data) => active && setReport(data))
      .catch((e) => active && setError(e.message));
    return () => {
      active = false;
    };
  }, [getAuthHeader, reportId]);

  useEffect(() => {
    if (!report) return;
    const previous = document.title;
    // The browser uses the page title as the PDF's default file name.
    document.title = `TeachMate report - ${report.stats.lesson} - ${new Date(report.created_at).toISOString().slice(0, 10)}`;
    return () => {
      document.title = previous;
    };
  }, [report]);

  const showEvidence = (evidenceId) => {
    const el = document.getElementById(`ev-${evidenceId}`);
    if (el) {
      el.scrollIntoView({ behavior: "smooth", block: "center" });
      setHighlight(evidenceId);
    }
  };

  if (error) {
    return (
      <div className="tr-page">
        <div className="tr-message tr-error">{error}</div>
        <Link to={`/l/${id}/dashboard`}>Back to the dashboard</Link>
      </div>
    );
  }
  if (!report) return <div className="tr-page tr-message">Loading report…</div>;

  const { stats, sections, citations, grounding } = report;
  const md = (text) => <Markdown text={text} citations={citations} onCite={showEvidence} />;
  const evidenceIds = Object.keys(citations).sort((a, b) => Number(a.slice(1)) - Number(b.slice(1)));

  return (
    <div className="tr-page">
      <div className="tr-toolbar">
        <Link to={`/l/${id}/dashboard`} className="tr-btn">
          <FiArrowLeft /> Back to dashboard
        </Link>
        <div className="tr-toolbar-actions">
          <button type="button" className="tr-btn" onClick={() => window.print()} title="Print this page">
            <FiPrinter /> Print
          </button>
          <button type="button" className="tr-btn tr-btn-primary" onClick={download} disabled={downloading} title="Download a designed A4 PDF of this report">
            <FiDownload /> {downloading ? "Preparing PDF…" : "Download PDF"}
          </button>
        </div>
      </div>
      {downloadError && <div className="tr-message tr-error tr-download-error">{downloadError}</div>}

      <article className="tr-report">
        <div className="tr-header">
          <div className="tr-eyebrow">TeachMate lesson report</div>
          <h1>{stats.lesson}</h1>
          <div className="tr-meta">
            {[stats.course, `${stats.minutes} min video`, `Generated ${formatDate(report.created_at)}`].filter(Boolean).join(" · ")}
          </div>
        </div>

        <div className="tr-stats">
          <div className="tr-stat">
            <strong>{stats.responders}</strong>
            <span>
              of {stats.watched} students gave feedback ({stats.participation_pct}%)
            </span>
          </div>
          {STATES.map(([key, label]) => (
            <div key={key} className={`tr-stat tr-stat-${key}`}>
              <strong>{stats.states[key]}</strong>
              <span>reported {label}</span>
            </div>
          ))}
          <div className="tr-stat">
            <strong>{stats.bookmarks}</strong>
            <span>saved reflections</span>
          </div>
        </div>

        <div className="tr-headline">{md(sections.headline)}</div>

        <Section title="At a glance">
          <ul>
            {sections.at_a_glance.map((item, i) => (
              <li key={i}>{md(item)}</li>
            ))}
          </ul>
        </Section>

        <Section title="Key moments">
          {sections.key_moments.map((moment, i) => (
            <div key={i} className="tr-moment">
              <div className="tr-moment-head">
                <span className="tr-window">{moment.window}</span>
                <h3>{moment.title}</h3>
              </div>
              {md(moment.what_happened)}
              {moment.students_said && (
                <div className="tr-students-said">
                  <span>What students said</span>
                  {md(moment.students_said)}
                </div>
              )}
            </div>
          ))}
        </Section>

        <Section title="What worked">
          <ul>
            {sections.what_worked.map((item, i) => (
              <li key={i}>{md(item)}</li>
            ))}
          </ul>
        </Section>

        <Section title="Your reflections so far">
          <ul>
            {sections.reflections.map((item, i) => (
              <li key={i}>{md(item)}</li>
            ))}
          </ul>
        </Section>

        <Section title="Questions to explore">
          <ul className="tr-questions">
            {sections.open_questions.map((item, i) => (
              <li key={i}>{md(item)}</li>
            ))}
          </ul>
        </Section>

        <Section title="Options to consider">
          <p className="tr-note">Ideas you can adopt, adapt or reject. You know your class best.</p>
          {sections.strategies.map((strategy, i) => (
            <div key={i} className="tr-strategy">
              <div className="tr-strategy-option">{md(strategy.option)}</div>
              {strategy.based_on && (
                <div className="tr-strategy-row">
                  <span>Based on</span>
                  {md(strategy.based_on)}
                </div>
              )}
              <div className="tr-strategy-row">
                <span>Responds to</span>
                {md(strategy.addresses)}
              </div>
              <div className="tr-strategy-row">
                <span>How to tell if it helped</span>
                {md(strategy.check)}
              </div>
            </div>
          ))}
        </Section>

        <Section title="Data behind this report">
          <p className="tr-note">
            {grounding.grounded ? (
              <span className="tr-grounding ok">
                <FiCheckCircle /> All {grounding.checked_numbers} numbers in this report were checked against your class data.
              </span>
            ) : (
              <span className="tr-grounding warn">
                <FiAlertTriangle /> {grounding.unsupported.length + grounding.unknown_ids.length} statement(s) couldn't be verified against the data. Please check them on the
                dashboard.
              </span>
            )}{" "}
            Each [E#] in the text refers to one of these facts, computed from the dashboard data.
          </p>
          <ol className="tr-evidence">
            {evidenceIds.map((evidenceId) => (
              <li key={evidenceId} id={`ev-${evidenceId}`} className={highlight === evidenceId ? "highlight" : undefined}>
                <strong>{evidenceId}</strong> {citations[evidenceId]}
              </li>
            ))}
          </ol>
        </Section>

        <div className="tr-footer">
          Generated by TeachMate (Google Gemini, {report.model}). It describes patterns in voluntary student feedback; interpretations and decisions are yours.
        </div>
      </article>
    </div>
  );
}
